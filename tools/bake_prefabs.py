"""Bake a game's prefabs/*.txt into baked_prefabs.inc (the editor's built-in prefabs; core/uied.cpp includes it).
Usage: python3 -I tools/bake_prefabs.py [prefabs dir] [output]
Defaults: games/nfsu2/prefabs -> build/gen/baked_prefabs.inc"""
import os, sys

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', 'games', 'nfsu2', 'prefabs')
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, '..', 'build', 'gen', 'baked_prefabs.inc')
os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)

def c_string(b):
    s = []
    for ch in b:
        if ch == 0x5C: s.append('\\\\')
        elif ch == 0x22: s.append('\\"')
        elif ch == 0x0A: s.append('\\n"\n    "')
        elif ch == 0x0D: continue
        elif 0x20 <= ch < 0x7F: s.append(chr(ch))
        else: s.append('\\%03o' % ch)
    return '"' + ''.join(s) + '"'

names = sorted(f for f in os.listdir(src) if f.lower().endswith('.txt') and not f.startswith('_')) if os.path.isdir(src) else []
lines = ['// Generated by tools/bake_prefabs.py from %s - do not edit.' % os.path.relpath(src, os.path.join(here, '..')).replace(os.sep, '/'), 'static const BakedPrefab kBakedPrefabs[] = {']
for f in names:
    lines.append('  {%s,\n    %s},' % (c_string(f[:-4].encode('latin1')), c_string(open(os.path.join(src, f), 'rb').read())))
lines.append('  {nullptr, nullptr}')
lines.append('};')
new = '\n'.join(lines) + '\n'
if not os.path.exists(out) or open(out).read() != new:
    open(out, 'w').write(new)
print('baked %d prefab(s): %s' % (len(names), ', '.join(n[:-4] for n in names)))
